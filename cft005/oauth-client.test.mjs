import assert from 'node:assert/strict';
import {safeReturn,assertClientClaim,pkce,authorizeUrl} from './oauth-client.mjs';
import {webcrypto} from 'node:crypto';
globalThis.crypto ??= webcrypto;
const expectReject=(f)=>assert.throws(f);
assert.equal(safeReturn('https://a.example/callback',['https://a.example']),'https://a.example/callback');
expectReject(()=>safeReturn('https://evil.example/callback',['https://a.example']));
expectReject(()=>safeReturn('https://a.example@evil.example/callback',['https://a.example']));
expectReject(()=>safeReturn('https://a.example/callback#token',['https://a.example']));
assert.equal(assertClientClaim({client_id:'A',sub:'user-1'},'A','user-1'),true);
expectReject(()=>assertClientClaim({client_id:'B',sub:'user-1'},'A','user-1'));
expectReject(()=>assertClientClaim({client_id:'A',sub:'user-2'},'A','user-1'));
const p=await pkce();
assert.match(p.verifier,/^[A-Za-z0-9_-]{43}$/);
assert.match(p.challenge,/^[A-Za-z0-9_-]{43}$/);
assert.equal(p.method,'S256');
const url=new URL(authorizeUrl({issuer:'https://example.supabase.co',clientId:'A',redirectUri:'https://a.example/callback',state:'random-state',challenge:p.challenge}));
assert.equal(url.pathname,'/auth/v1/oauth/authorize');
assert.equal(url.searchParams.get('code_challenge_method'),'S256');
assert.equal(url.searchParams.get('response_type'),'code');
console.log('CFT-005: 12 assertions PASS (local only; no real SSO).');
